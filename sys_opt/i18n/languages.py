def get_language(code):
    """Return the language metadata dict, or None for an unknown code."""
    return LANGUAGES.get(code)


def build_translator(lang_code):
    """Return ``t(key) -> str``; unknown or empty keys fall back to English."""
    strings = LANGUAGES.get(lang_code, {}).get("strings", {})
    english = LANGUAGES["en"]["strings"]

    def translate(key):
        value = strings.get(key)
        if value is None or str(value).strip() == "":
            value = english.get(key, "{%s}" % key)
        return value

    return translate


def validate_languages():
    """Return a list of issues; an empty list means every language is complete.

    Checks that every language defines exactly the same key set as English and
    that no value is empty, guaranteeing zero missing keys across languages.
    """
    issues = []
    reference = set(LANGUAGES["en"]["strings"].keys())
    for code, meta in LANGUAGES.items():
        keys = set(meta.get("strings", {}).keys())
        for key in sorted(reference - keys):
            issues.append("[%s] missing key: %s" % (code, key))
        for key in sorted(keys - reference):
            issues.append("[%s] unexpected extra key: %s" % (code, key))
        for key in sorted(keys & reference):
            value = meta["strings"].get(key)
            if value is None or str(value).strip() == "":
                issues.append("[%s] empty value for key: %s" % (code, key))
    return issues


def _locale_to_language_code(raw):
    """Map a locale string (e.g. 'it_IT.UTF-8') to a supported code or None."""
    if not raw:
        return None
    lowered = str(raw).lower().replace("-", "_")
    primary = lowered.split("_")[0].split(".")[0]
    if primary in _SUPPORTED_LANGUAGE_CODES:
        return primary
    if primary == "zh":
        return "zh"
    return None


def detect_system_language():
    """Detect the host locale and map it to a supported language code.

    Checks (in order): env vars, locale module, Windows UI language. Falls
    back to 'en' when nothing is detectable.
    """
    hints = []
    for var in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        value = os.environ.get(var)
        if value:
            hints.append(value)
    try:
        locale_hint, _encoding = locale.getlocale()
        if locale_hint:
            hints.append(locale_hint)
    except Exception:
        pass
    if os.name == "nt":
        try:
            import ctypes

            lang_id = int(ctypes.windll.kernel32.GetUserDefaultUILanguage()) & 0x3FF
            code = _WINDOWS_LANGID_MAP.get(lang_id)
            if code:
                return code
        except Exception:
            pass
    for hint in hints:
        code = _locale_to_language_code(hint)
        if code:
            return code
    return "en"
